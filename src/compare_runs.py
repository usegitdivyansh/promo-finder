import os
import sys
import json
import argparse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from src.common import load, load_dir
from src.evaluate import gold_eval
from src.report import run_summary


def mean(arr):
    if not arr:
        return None
    return round(sum(arr) / len(arr), 2)


def stats(run_dir, gold):
    res = {"run": os.path.basename(os.path.normpath(run_dir))}
    shots = {}
    for d in load_dir(os.path.join(run_dir, "04_shots")):
        shots[d["episode"]] = len(d["shots"])
    res["shots_per_episode"] = shots
    res["shots_total"] = sum(shots.values())
    sel = load(os.path.join(run_dir, "08_selected.json"))
    summ = run_summary(run_dir, {"llm": {}}, sel)
    res["fill"] = f"{summ.get('scripts_filled', 0)}/{summ.get('scripts_written', 0)} ({summ.get('fill_rate', 0)})"
    scored = load(os.path.join(run_dir, "07_scored.json"))
    res["eligible_promos"] = len(scored)
    res["selected_promos"] = len(sel["selected"])
    cl = []
    for p in sel["selected"]:
        if p["scores"]["clarity_source"] == "judge_fresh":
            cl.append(p["scores"]["clarity"])
    res["fresh_clarity_selected"] = mean(cl)
    cl = []
    for p in scored:
        if p["scores"]["clarity_source"] == "judge_fresh":
            cl.append(p["scores"]["clarity"])
    res["fresh_clarity_all_scored"] = mean(cl)
    finals = load(os.path.join(run_dir, "09_final", "promos.json"))
    ge = gold_eval(gold, finals, scored)
    hits = 0
    for g in ge:
        if g["hit"]:
            hits += 1
    res["gold_hits"] = f"{hits}/{len(ge)}"
    res["gold_best_iou"] = {}
    for g in ge:
        res["gold_best_iou"][g["gold_id"]] = g["best_iou"]
    c = load(os.path.join(run_dir, "10_baseline.json"))["comparison"]
    res["tool_top15"] = c["mean_total_tool_top15"]
    res["baseline_top15"] = c["mean_total_baseline_top15"]
    res["baseline_gap"] = round(c["mean_total_tool_top15"] - c["mean_total_baseline_top15"], 2)
    nb = c.get("mean_total_baseline_top15_no_spoilers")
    res["baseline_top15_no_spoilers"] = nb
    if nb is not None:
        res["baseline_gap_no_spoilers"] = round(c["mean_total_tool_top15"] - nb, 2)
    res["drops"] = summ["drops_by_reason"]
    # every call recorded for this folder; cached rows show what the run would cost from scratch
    by = {}
    with open(os.path.join(run_dir, "usage.jsonl"), encoding="utf-8") as f:
        for ln in f:
            r = json.loads(ln)
            m = by.setdefault(r["model"], {"calls": 0, "cached": 0, "prompt_tokens": 0, "completion_tokens": 0, "cost_usd": 0.0})
            m["calls"] += 1
            if r.get("cached"):
                m["cached"] += 1
            m["prompt_tokens"] += r["prompt_tokens"]
            m["completion_tokens"] += r["completion_tokens"]
            m["cost_usd"] = round(m["cost_usd"] + r.get("cost_usd", 0), 6)
    res["usage_by_model"] = by
    cost = 0.0
    for m in by.values():
        cost += m["cost_usd"]
    res["cost_usd"] = round(cost, 6)
    res["selected"] = []
    for p in sel["selected"]:
        segs = []
        for s in p["segments"]:
            segs.append(f"ep{s['episode']} {int(s['start'])//60:02d}:{int(s['start'])%60:02d}-{int(s['end'])//60:02d}:{int(s['end'])%60:02d}")
        res["selected"].append(f"{p['final_id']} {p['template']} {round(p['total_duration_sec'])}s total {p['scores']['total']} clarity {p['scores']['clarity']} | {' | '.join(segs)} | hook: {p['hook']} | cliff: {p['cliffhanger']}")
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", nargs="+", required=True)
    ap.add_argument("--gold", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    gold = load(a.gold)
    arr = []
    for r in a.runs:
        arr.append(stats(r, gold))
    rows = [("shots per episode", "shots_per_episode"), ("shots total", "shots_total"), ("script fill rate", "fill"),
            ("promos eligible / selected", None), ("fresh-viewer clarity, selected", "fresh_clarity_selected"),
            ("fresh-viewer clarity, all scored", "fresh_clarity_all_scored"), ("gold hits (IoU >= 0.5)", "gold_hits"),
            ("gold best IoU", "gold_best_iou"), ("tool top-15 mean total", "tool_top15"), ("baseline top-15 mean", "baseline_top15"),
            ("gap vs baseline", "baseline_gap"), ("baseline mean, no spoiler clips", "baseline_top15_no_spoilers"),
            ("gap vs no-spoiler baseline", "baseline_gap_no_spoilers"), ("paid cost (USD)", "cost_usd")]
    out = ["# Synthetic show: run comparison", "", "Generated by `src/compare_runs.py` from the run folders. Nothing is hand-edited.", ""]
    out.append("| metric | " + " | ".join(r["run"] for r in arr) + " |")
    out.append("|---|" + "---|" * len(arr))
    for label, k in rows:
        vals = []
        for r in arr:
            if k is None:
                vals.append(f"{r['eligible_promos']} / {r['selected_promos']}")
            else:
                vals.append(str(r.get(k, "")).replace("|", "/"))
        out.append(f"| {label} | " + " | ".join(vals) + " |")
    for r in arr:
        out.append("")
        out.append(f"## {r['run']}")
        out.append("")
        out.append("Usage by model (cached rows were paid for by an earlier run):")
        out.append("")
        out.append("| model | calls | cached | prompt tok | completion tok | cost $ |")
        out.append("|---|---|---|---|---|---|")
        for m, v in r["usage_by_model"].items():
            out.append(f"| {m} | {v['calls']} | {v['cached']} | {v['prompt_tokens']} | {v['completion_tokens']} | {v['cost_usd']} |")
        out.append("")
        out.append("Drops: " + ", ".join(f"{k} {v}" for k, v in r["drops"].items()))
        out.append("")
        out.append("Selected promos:")
        for s in r["selected"]:
            out.append(f"- {s}")
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out[:len(rows) + 6]))


if __name__ == "__main__":
    main()
